"""
Figure generation for the paper, driven directly by experiment_5f_runs.csv.

The point of this module is that every number that ends up in the paper --
the histogram bars, the scale factor of the theoretical curve, and the
figures quoted in the caption -- is derived from the runs CSV rather than
typed by hand.

Usage:
    python main.py --export-tikz adam_conv_lr0p05/experiment_5f_runs.csv
"""

import csv
import math
from pathlib import Path
from typing import Dict, List, Optional

# A run counts as successful iff it was not aborted by the loss rule at
# t=10,000; those runs are trained for the full iteration budget.
LOSS_ABORT = "loss-abort"


def load_successful_runs(runs_csv):
    """Return (all_rows, successful_rows).

    A run is successful iff it (a) was not aborted by the loss rule at
    t=10,000 and (b) was never stopped early by the optimizer-specific
    convergence test, i.e. it ran the full iteration budget. Condition (b)
    matters: the early-stop test can fire within the first 1000 iterations,
    before |b2-b1| has started to move, and such runs would otherwise
    contribute a spurious spike at zero.
    """
    with open(runs_csv, newline="") as f:
        rows = list(csv.DictReader(f))
    ok = [
        r for r in rows
        if r["stop_reason"] != LOSS_ABORT and int(r["t_hit"]) == -1
    ]
    return rows, ok


def bias_histogram(values: List[float], bin_width: float, x_max: float):
    """Bin |b2-b1| into [0, x_max] using bins of width bin_width.

    Returns (counts, n_overflow). The trailing bin at x_max is kept so that
    pgfplots' `ybar interval` has a closing coordinate.
    """
    n_bins = int(round(x_max / bin_width))
    counts = [0] * (n_bins + 1)
    overflow = 0
    for v in values:
        i = int(v / bin_width)
        if i > n_bins:
            overflow += 1
        else:
            counts[i] += 1
    return counts, overflow


def _fmt_coordinates(counts: List[int], bin_width: float, per_line: int = 4) -> str:
    cells = [
        "({:.1f}, {})".format(i * bin_width, c) for i, c in enumerate(counts)
    ]
    width = max(len(c) for c in cells)
    lines = []
    for start in range(0, len(cells), per_line):
        chunk = [c.ljust(width) for c in cells[start:start + per_line]]
        lines.append("                " + " ".join(chunk).rstrip())
    return "\n".join(lines)


def export_bias_hist_tikz(
    runs_csv,
    out_tex,
    bin_width: float = 0.1,
    x_max: float = 2.0,
    y_max: Optional[int] = None,
    out_png: Optional[str] = None,
) -> Dict[str, float]:
    """Write the TikZ figure for the terminal-numerator histogram.

    Returns a dict of the statistics quoted in the caption, so they can be
    checked against the text instead of being trusted.
    """
    all_rows, runs = load_successful_runs(runs_csv)
    values = [abs(float(r["b2_T"]) - float(r["b1_T"])) for r in runs]
    n = len(values)
    if n == 0:
        raise ValueError(f"no successful runs found in {runs_csv}")

    counts, overflow = bias_histogram(values, bin_width, x_max)
    scale = n * bin_width
    if y_max is None:
        y_max = int(math.ceil(max(counts) / 10.0) * 10)

    deltas = [float(r["convergence_delta"]) for r in runs if r["convergence_delta"]]
    stds = [float(r["convergence_std"]) for r in runs if r["convergence_std"]]
    n_ge_one = sum(1 for v in values if v >= 1.0)

    stats = {
        "runs_total": len(all_rows),
        "runs_successful": n,
        "runs_loss_abort": sum(1 for r in all_rows if r["stop_reason"] == LOSS_ABORT),
        "counts_sum": sum(counts),
        "overflow_beyond_x_max": overflow,
        "value_max": max(values),
        "value_min": min(values),
        "scale_factor": scale,
        "n_ge_one": n_ge_one,
        "pct_ge_one": 100.0 * n_ge_one / n,
        "max_convergence_delta": max(deltas) if deltas else float("nan"),
        "max_convergence_std": max(stds) if stds else float("nan"),
        "runs_early_stopped": sum(
            1 for r in all_rows
            if r["stop_reason"] != LOSS_ABORT and int(r["t_hit"]) != -1
        ),
        "t_last_min": min(int(r["t_last"]) for r in runs),
        "t_last_max": max(int(r["t_last"]) for r in runs),
        "all_correct_quadrant": all(
            float(r["w1_0"]) > 0 > float(r["w2_0"]) for r in runs
        ),
    }

    xtick = ",".join(
        ("{:g}".format(v) for v in _ticks(x_max))
    )
    body = r"""% Generated by wide_network_experiments.figures.export_bias_hist_tikz
% Source: {src}
% {n} successful runs of {total} ({aborted} aborted by the loss rule at
% t=10,000; {early} stopped early by the convergence test and excluded).
% Bin width {bw}; all values fall inside [0, {xmax}] ({ovf} beyond).
% Caption figures: {pct:.1f}% of runs end with numerator >= 1;
% max change over final 10,000 iterations = {delta:.3g};
% max std over final 11 samples = {std:.3g}.
\begin{{figure}}[ht]
    \centering
    \begin{{tikzpicture}}
        \begin{{axis}}[
            width=8.5cm,
            height=7cm,
            ymin=0,
            ymax={ymax},
            xmin=0,
            xmax={xmax},
            xlabel={{}},
            axis lines=left,
            grid=both,
            grid style={{dashed, gray!30}},
            legend pos=north east,
            bar width={bw},
            ybar interval,
            xtick={{{xtick}}}
        ]
            \addplot[fill=red!30, draw=red!70] coordinates {{
{coords}
            }};
            \addlegendentry{{$|b_2^{{(t)}}-b_1^{{(t)}}|$}}

            % Theoretical density f_B, scaled by (number of runs) x (bin width).
            \addplot[
                blue,
                sharp plot,
                line width=1.5pt,
                domain=0:{xmax},
                samples=200
            ] {{
                {scale}*2*sqrt(2/pi)
                * exp(-x^2/2)
                * erfcapprox(x/sqrt(2))
            }};
            \addlegendentry{{$f_B(x)$}}
        \end{{axis}}
    \end{{tikzpicture}}
    \caption{{TODO}}
    \label{{fig:histogram_adam}}
\end{{figure}}
""".format(
        src=Path(runs_csv).as_posix(),
        n=n,
        total=len(all_rows),
        aborted=stats["runs_loss_abort"],
        early=stats["runs_early_stopped"],
        bw=_fmt_num(bin_width),
        xmax=_fmt_num(x_max),
        ovf=overflow,
        pct=stats["pct_ge_one"],
        delta=stats["max_convergence_delta"],
        std=stats["max_convergence_std"],
        ymax=y_max,
        xtick=xtick,
        coords=_fmt_coordinates(counts, bin_width),
        scale="{:g}".format(scale),
    )

    Path(out_tex).write_text(body)

    if out_png:
        try:
            import matplotlib
            matplotlib.use("Agg")
            import matplotlib.pyplot as plt
        except ImportError:
            print(f"matplotlib not available; skipping {out_png}")
            return stats

        edges = [i * bin_width for i in range(len(counts))]
        plt.figure(figsize=(8, 5))
        plt.bar(edges, counts, width=bin_width, align="edge",
                color="#f4a3a3", edgecolor="#c04040")
        xs = [i * x_max / 400 for i in range(401)]
        fb = [scale * 2 * math.sqrt(2 / math.pi) * math.exp(-x * x / 2)
              * math.erfc(x / math.sqrt(2)) for x in xs]
        plt.plot(xs, fb, color="blue", linewidth=1.5, label="$f_B(x)$")
        plt.xlabel("|b2 - b1|")
        plt.ylabel("Count")
        plt.legend()
        plt.tight_layout()
        plt.savefig(out_png, dpi=200)
        plt.close()

    return stats


def _fmt_num(v: float) -> str:
    """Format a float for LaTeX, keeping one decimal for whole numbers."""
    return "{:.1f}".format(v) if float(v).is_integer() else "{:g}".format(v)


def _ticks(x_max: float) -> List[float]:
    ticks, v = [], 0.0
    while v <= x_max + 1e-9:
        ticks.append(v)
        v += 0.5
    return ticks
